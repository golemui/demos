import { useState } from 'react';
import { GuiForm } from '@golemui/gui-react';
import type { FormSubmitEvent } from '@golemui/core';
import { recover, type RecoverResult } from './recover';
import { SAMPLES } from './samples';
import { DecisionsPanel } from './DecisionsPanel';
import { DemoShell } from './_shared/DemoShell';

export default function App() {
  const [text, setText] = useState(SAMPLES[0].text);
  const [result, setResult] = useState<RecoverResult | null>(null);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [view, setView] = useState<'form' | 'json'>('form');
  const [submitted, setSubmitted] = useState<unknown>(null);

  async function build() {
    setBusy(true);
    setSubmitted(null);
    try {
      setResult(await recover(text));
      setError(null);
    } catch (e) {
      setError(e instanceof Error ? e.message : String(e));
    } finally {
      setBusy(false);
    }
  }

  return (
    <DemoShell demoName="Text to form">
      <div className="recovery">
        <section className="recovery__input">
          <div className="recovery__samples">
            {SAMPLES.map((s) => (
              <button key={s.name} type="button" onClick={() => setText(s.text)}>
                {s.name}
              </button>
            ))}
          </div>
          <textarea
            className="recovery__text"
            value={text}
            onChange={(e) => setText(e.target.value)}
            spellCheck={false}
          />
          <button type="button" className="recovery__build" onClick={build} disabled={busy || !text.trim()}>
            {busy ? 'Asking TypeSafe…' : 'Build the form'}
          </button>
          {error && <p className="recovery__error">{error}</p>}

          {result && <DecisionsPanel result={result} />}
        </section>

        <section className="recovery__output">
          {!result && (
            <p className="recovery__empty">
              Describe the form on the left and press <b>Build the form</b>. The model classifies each
              line; the code writes the definition. No JSON is generated by a model.
            </p>
          )}

          {result && (
            <>
              <div className="recovery__tabs">
                <button type="button" className={view === 'form' ? 'is-active' : ''} onClick={() => setView('form')}>
                  Rendered form
                </button>
                <button type="button" className={view === 'json' ? 'is-active' : ''} onClick={() => setView('json')}>
                  Definition (JSON)
                </button>
                <span className={`recovery__badge ${result.validation.valid ? 'is-valid' : 'is-invalid'}`}>
                  {result.validation.valid ? 'schema valid' : `${result.validation.errors.length} schema errors`}
                </span>
              </div>

              {view === 'form' && (
                <div className="recovery__form">
                  {/* A new definition object means a new form; `key` forces a clean mount. */}
                  <GuiForm
                    key={JSON.stringify(result.definition)}
                    config={{ formDef: result.definition }}
                    formSubmit={(e: FormSubmitEvent) => setSubmitted(e.data)}
                  />
                  {submitted != null && <pre className="recovery__submitted">{JSON.stringify(submitted, null, 2)}</pre>}
                </div>
              )}

              {view === 'json' && <pre className="recovery__json">{JSON.stringify(result.definition, null, 2)}</pre>}
            </>
          )}
        </section>
      </div>
    </DemoShell>
  );
}
